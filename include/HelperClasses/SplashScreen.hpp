    inline void show()
    {
        auto &ctx = DisplayModule::Utilities::drawContext();
        auto &gfx = ctx.display;
        auto color = DisplayModule::DrawCommand::DrawColorPrimary();

        bool    tall     = ctx.height >= 128;
        int16_t logo     = tall ? LOGO_LARGE : LOGO_SMALL;
        uint8_t textSize = tall ? 2 : 1;
        int16_t gap      = tall ? 8 : 4;

        const char *name  = "WyrdWyrks";
        int16_t     textW = 9 * 6 * textSize - textSize; // 9 glyphs, minus trailing spacing
        int16_t     textH = 8 * textSize;
        int16_t     top   = (ctx.height - (logo + gap + textH)) / 2;

        gfx->fillScreen(0);
        gfx->drawBitmap((ctx.width - logo) / 2, top, tall ? logo88 : logo44, logo, logo, color);

        gfx->setTextSize(textSize);
        gfx->setCursor((ctx.width - textW) / 2, top + logo + gap);
        gfx->print(name);
        gfx->setTextSize(1);

        DisplayModule::Utilities::onRenderComplete();
        shownAtUs = esp_timer_get_time();
    }

    // Blocks until the splash has been up for at least minMs.
    inline void waitMinimum(uint32_t minMs = 500)
    {
        int64_t remainingUs = int64_t(minMs) * 1000 - (esp_timer_get_time() - shownAtUs);
        if (remainingUs > 0)
        {
            vTaskDelay(pdMS_TO_TICKS(remainingUs / 1000) + 1);
        }
    }
